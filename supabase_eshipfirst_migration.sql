-- ==============================================================================
-- eShipFirst (Packzy / Steadfast API v1) Courier Integration Migration
-- Safe, additive, idempotent migration — preserves all existing columns & data.
-- ==============================================================================

-- 1. Add minimal courier tracking columns to existing public.orders table
alter table public.orders
  add column if not exists courier_provider text,
  add column if not exists consignment_id text,
  add column if not exists tracking_code text,
  add column if not exists courier_booking_status text,
  add column if not exists courier_delivery_status text,
  add column if not exists courier_return_status text,
  add column if not exists courier_submitted_at timestamp with time zone,
  add column if not exists last_status_checked_at timestamp with time zone,
  add column if not exists courier_response_reference jsonb;

create index if not exists idx_orders_consignment_id on public.orders (consignment_id);
create index if not exists idx_orders_tracking_code on public.orders (tracking_code);
create index if not exists idx_orders_courier_booking_status on public.orders (courier_booking_status);

-- 2. Dedicated courier parcels table with strict duplicate prevention per order
create table if not exists public.eshipfirst_parcels (
  id bigint generated by default as identity primary key,
  order_id text not null unique,
  order_db_id bigint references public.orders(id) on delete set null,
  courier_provider text not null default 'eshipfirst',
  consignment_id text,
  tracking_code text,
  invoice text not null,
  recipient_name text not null,
  recipient_phone text not null,
  recipient_address text not null,
  cod_amount numeric not null default 0,
  courier_booking_status text not null default 'pending', -- pending, submitted, booked, failed
  courier_delivery_status text,                           -- exact raw API delivery_status
  courier_return_status text,                             -- exact raw API return_status
  courier_submitted_at timestamp with time zone,
  last_status_checked_at timestamp with time zone,
  last_error text,
  courier_response_reference jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_eshipfirst_parcels_cid on public.eshipfirst_parcels (consignment_id);
create index if not exists idx_eshipfirst_parcels_phone on public.eshipfirst_parcels (recipient_phone);
create index if not exists idx_eshipfirst_parcels_delivery_status on public.eshipfirst_parcels (courier_delivery_status);

-- 3. Sanitized API request/response audit logs (never stores secrets)
create table if not exists public.eshipfirst_logs (
  id bigint generated by default as identity primary key,
  action text not null,
  endpoint text,
  order_id text,
  consignment_id text,
  http_status integer,
  success boolean not null default false,
  message text,
  request_summary jsonb,
  response_summary jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_eshipfirst_logs_created_at on public.eshipfirst_logs (created_at desc);

-- 4. Enable RLS with service-role full access (secrets & writes stay server-side)
alter table public.eshipfirst_parcels enable row level security;
alter table public.eshipfirst_logs enable row level security;

drop policy if exists "Allow read eshipfirst_parcels" on public.eshipfirst_parcels;
create policy "Allow read eshipfirst_parcels" on public.eshipfirst_parcels
  for select to public using (true);
